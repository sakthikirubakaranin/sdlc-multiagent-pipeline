    # ── ZIP builder ───────────────────────────────────────────────────────────

    def _create_zip(self, root: Path, zip_path: Path) -> int:
        """Zip every file under root except the zip itself and uploads/."""
        count = 0
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
            for fp in sorted(root.rglob("*")):
                if fp == zip_path:
                    continue
                if any(part in {"uploads", "__pycache__", ".git", "node_modules"}
                       for part in fp.parts):
                    continue
                if fp.suffix in {".pyc", ".pyo"}:
                    continue
                if fp.is_file():
                    arcname = fp.relative_to(root)
                    zf.write(fp, arcname)
                    count += 1
        return count

    # ── Manifest ──────────────────────────────────────────────────────────────

    def _build_manifest(self, root: Path, project: str, cloud: str, timestamp: str) -> dict:
        files = []
        total_bytes = 0
        for fp in sorted(root.rglob("*")):
            if fp.is_file() and not any(
                p in {"uploads", "__pycache__", ".git", "node_modules"} for p in fp.parts
            ) and fp.suffix not in {".pyc", ".pyo"}:
                size = fp.stat().st_size
                total_bytes += size
                files.append({
                    "path":  str(fp.relative_to(root)),
                    "size":  size,
                    "ext":   fp.suffix.lstrip(".") or fp.name,
                })
        return {
            "project":    project,
            "cloud":      cloud,
            "timestamp":  timestamp,
            "total_files": len(files),
            "total_size":  total_bytes,
            "total_size_human": self._human_size(total_bytes),
            "files":      files,
        }

    @staticmethod
    def _human_size(n: int) -> str:
        for unit in ["B", "KB", "MB", "GB"]:
            if n < 1024:
                return f"{n:.1f} {unit}"
            n /= 1024
        return f"{n:.1f} TB"
