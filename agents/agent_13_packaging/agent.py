"""
Agent 13 — Packaging & Export Agent
────────────────────────────────────
Final step of every pipeline run. Bundles all generated outputs into a
ready-to-run artifact the developer can immediately use:

  localhost  → ZIP archive  +  start.sh / stop.sh  +  Electron DMG scaffold
  gcp/aws/azure → ZIP with Terraform + CI/CD ready for `terraform apply`

No Claude API call needed — this agent is pure Python file I/O.
Model tier: haiku (but actually makes zero Claude calls)
"""
from __future__ import annotations

